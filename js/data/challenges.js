/**
 * يُرجع تحدي الأسبوع بناءً على رقم الأسبوع الحالي من السنة،
 * حتى يدور التحدي تلقائيًا دون أي إعداد.
 */
export function getWeeklyChallenge(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 1);
  const week = Math.floor((date - start) / (7 * 24 * 60 * 60 * 1000));
  return challenges[week % challenges.length];
}

/** يُرجع ترتيب التحدي في الدورة (0-based) لعرض تسمية الأسبوع. */
export function getWeekIndex(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 1);
  return Math.floor((date - start) / (7 * 24 * 60 * 60 * 1000)) % challenges.length;
}
